from collections import Counter
from pathlib import Path

import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    make_scorer,
)
from sklearn.model_selection import (
    StratifiedKFold,
    cross_validate,
    train_test_split,
)
from sklearn.preprocessing import LabelEncoder


BASE_DIR = Path(__file__).resolve().parent
DATA_PATH = BASE_DIR / "health_data.csv"
REPORT_PATH = BASE_DIR / "docs" / "evaluation.md"
FEATURE_COLUMNS = [
    "Age",
    "Gender",
    "BMI",
    "BP",
    "Sugar",
    "Cholesterol",
    "Smoking",
    "FamilyHistory",
]
CATEGORICAL_COLUMNS = ["Gender", "Smoking", "FamilyHistory"]
SEED = 42


def main() -> None:
    data = pd.read_csv(DATA_PATH)
    required_columns = FEATURE_COLUMNS + ["Disease"]
    missing_columns = set(required_columns) - set(data.columns)
    if missing_columns:
        raise ValueError(f"Dataset is missing columns: {sorted(missing_columns)}")
    if data[required_columns].isna().any().any():
        raise ValueError("Dataset contains missing values in required columns.")

    features = data[FEATURE_COLUMNS].copy()
    for column in CATEGORICAL_COLUMNS:
        encoder = LabelEncoder()
        features[column] = encoder.fit_transform(features[column])

    target_encoder = LabelEncoder()
    target = target_encoder.fit_transform(data["Disease"])
    class_names = target_encoder.classes_
    class_ids = list(range(len(class_names)))

    x_train, x_test, y_train, y_test = train_test_split(
        features,
        target,
        test_size=0.2,
        random_state=SEED,
        stratify=target,
    )
    model = RandomForestClassifier(n_estimators=100, random_state=SEED)
    model.fit(x_train, y_train)
    predictions = model.predict(x_test)

    report = classification_report(
        y_test,
        predictions,
        labels=class_ids,
        target_names=class_names,
        output_dict=True,
        zero_division=0,
    )
    matrix = confusion_matrix(y_test, predictions, labels=class_ids)

    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    cv_scores = cross_validate(
        RandomForestClassifier(n_estimators=100, random_state=SEED),
        features,
        target,
        cv=cv,
        scoring={
            "accuracy": "accuracy",
            "macro_f1": make_scorer(
                f1_score,
                average="macro",
                labels=class_ids,
                zero_division=0,
            ),
        },
    )
    class_counts = Counter(data["Disease"])

    lines = [
        "# Evaluation",
        "",
        "Generated by `python evaluate_model.py` from `health_data.csv`.",
        "",
        "This evaluates a newly fitted Random Forest on the CSV. It does not "
        "evaluate the committed `model.pkl`: `train_model.py` trains from its "
        "own hard-coded 40-row dataset and does not read this CSV.",
        "",
        "The CSV has 15 rows and no documented external or clinical source. "
        "`train_model.py` describes its matching first 15 rows as original "
        "and its 25 additional rows as synthetic; provenance for the first 15 "
        "is not provided.",
        "",
        "## Data",
        "",
        f"- Rows: {len(data)}",
        "- Class counts: "
        + ", ".join(f"{name}: {class_counts[name]}" for name in class_names),
        "",
        "## Stratified 80/20 holdout",
        "",
        f"Random seed: `{SEED}`. Model: `RandomForestClassifier("
        "n_estimators=100, random_state=42)`.",
        "",
        f"- Accuracy: **{accuracy_score(y_test, predictions):.3f}**",
        "- Macro-F1: **{:.3f}**".format(report["macro avg"]["f1-score"]),
        "",
        "| Class | Precision | Recall | F1 | Support |",
        "|---|---:|---:|---:|---:|",
    ]
    for class_name in class_names:
        class_report = report[class_name]
        lines.append(
            f"| {class_name} | {class_report['precision']:.3f} | "
            f"{class_report['recall']:.3f} | {class_report['f1-score']:.3f} | "
            f"{int(class_report['support'])} |"
        )
    lines.extend(
        [
            f"| **Macro average** | {report['macro avg']['precision']:.3f} | "
            f"{report['macro avg']['recall']:.3f} | "
            f"{report['macro avg']['f1-score']:.3f} | "
            f"{int(report['macro avg']['support'])} |",
            "",
            "Confusion matrix (rows = actual, columns = predicted; class order "
            "shown in the headers):",
            "",
            "| Actual \ Predicted | "
            + " | ".join(class_names)
            + " |",
            "|---|"
            + "|".join("---:" for _ in class_names)
            + "|",
        ]
    )
    for class_name, row in zip(class_names, matrix):
        lines.append(
            f"| {class_name} | " + " | ".join(str(int(value)) for value in row) + " |"
        )

    lines.extend(
        [
            "",
            "## 5-fold stratified cross-validation",
            "",
            "Shuffled folds with random seed `42`; values are the mean ± "
            "population standard deviation across folds.",
            "",
            "Heart Disease has only 4 examples, fewer than 5 folds. Scikit-learn "
            "warns that at least one validation fold cannot contain that class, "
            "so these cross-validation estimates are unstable.",
            "",
            "| Metric | Mean ± std |",
            "|---|---:|",
            "| Accuracy | "
            f"{cv_scores['test_accuracy'].mean():.3f} ± "
            f"{cv_scores['test_accuracy'].std():.3f} |",
            "| Macro-F1 | "
            f"{cv_scores['test_macro_f1'].mean():.3f} ± "
            f"{cv_scores['test_macro_f1'].std():.3f} |",
            "",
            "## Interpretation",
            "",
            "These are resampling results on 15 small, unverified records, "
            "not clinical validation. The labels are supplied in the dataset "
            "rather than independently verified outcomes, and the source "
            "does not document a clinical labeling protocol. Scores should "
            "not be interpreted as diagnostic performance or expected "
            "real-world accuracy.",
            "",
        ]
    )

    output = "\n".join(lines)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(output, encoding="utf-8")
    print(output, end="")
    print(f"\nSaved report to {REPORT_PATH}")


if __name__ == "__main__":
    main()
